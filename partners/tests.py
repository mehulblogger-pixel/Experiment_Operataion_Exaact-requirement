from django.test import TestCase

from accounts.models import User
from .models import BusinessPartner
from .utils import pan_from_gstin, state_from_gstin, is_valid_gstin


class PartnerModelTests(TestCase):
    def test_code_autogenerated(self):
        p = BusinessPartner.objects.create(legal_name="Adani Green Energy", is_client=True)
        self.assertTrue(p.code.startswith("GEN-ADANI-"))

    def test_pan_and_state_from_gstin(self):
        p = BusinessPartner.objects.create(
            legal_name="X Ltd", is_client=True, gstin="24ADUPL3517E2ZJ"
        )
        self.assertEqual(p.pan, "ADUPL3517E")
        self.assertEqual(p.state, "Gujarat")

    def test_roles_label(self):
        p = BusinessPartner.objects.create(
            legal_name="Both Co", is_client=True, is_vendor=True
        )
        self.assertEqual(p.roles_label, "Client / Vendor")

    def test_gstin_helpers(self):
        self.assertTrue(is_valid_gstin("24ADUPL3517E2ZJ"))
        self.assertFalse(is_valid_gstin("BADGSTIN"))
        self.assertEqual(pan_from_gstin("24ADUPL3517E2ZJ"), "ADUPL3517E")
        self.assertEqual(state_from_gstin("27ABCDE1234F1Z5"), "Maharashtra")


class PartnerViewTests(TestCase):
    @classmethod
    def setUpTestData(cls):
        cls.user = User.objects.create_superuser("admin", "a@a.com", "pw")
        cls.client_p = BusinessPartner.objects.create(
            legal_name="Acme Ltd", is_client=True
        )
        cls.vendor_p = BusinessPartner.objects.create(
            legal_name="Bolt Works", is_vendor=True
        )

    def setUp(self):
        self.client.login(username="admin", password="pw")

    def test_client_list_shows_only_clients(self):
        resp = self.client.get("/partners/clients/")
        self.assertContains(resp, "Acme Ltd")
        self.assertNotContains(resp, "Bolt Works")

    def test_vendor_list_shows_only_vendors(self):
        resp = self.client.get("/partners/vendors/")
        self.assertContains(resp, "Bolt Works")
        self.assertNotContains(resp, "Acme Ltd")

    def test_detail_tabs_render(self):
        for tab in ["overview", "general", "registration", "addresses",
                    "contacts", "contracts", "purchase_orders", "projects",
                    "relationships", "notes", "timeline"]:
            resp = self.client.get(f"/partners/{self.client_p.pk}/?tab={tab}")
            self.assertEqual(resp.status_code, 200)

    def test_contract_po_and_line_item(self):
        self.client.post(f"/partners/{self.client_p.pk}/contract/add/",
                         {"contract_number": "C-1", "is_active": "on"})
        self.assertEqual(self.client_p.contracts.count(), 1)
        self.client.post(f"/partners/{self.client_p.pk}/po/add/",
                         {"po_number": "PO-1", "po_type": "ARC", "is_active": "on"})
        po = self.client_p.purchase_orders.first()
        self.assertIsNotNone(po)
        self.client.post(f"/partners/po/{po.pk}/",
                         {"description": "Mandays", "item_type": "MANDAYS",
                          "quantity": "50", "rate": "1000", "consumed": "5"})
        li = po.line_items.first()
        self.assertEqual(li.balance, 45)
        self.assertEqual(li.amount, 50000)

    def test_add_relationship(self):
        other = BusinessPartner.objects.create(legal_name="Parent Group", is_client=True)
        self.client.post(f"/partners/{self.client_p.pk}/relationship/add/",
                         {"relation_type": "SUBSIDIARY", "related": other.pk})
        self.assertEqual(self.client_p.relationships.count(), 1)

    def test_create_requires_a_role(self):
        resp = self.client.post("/partners/new/", {
            "legal_name": "No Role Ltd", "status": "ACTIVE", "country": "India",
        })
        self.assertContains(resp, "at least one role")

    def test_add_contact(self):
        self.client.post(f"/partners/{self.client_p.pk}/contact/add/", {
            "name": "Ravi", "designation": "Buyer", "mobile": "999",
        })
        self.assertEqual(self.client_p.contacts.count(), 1)
