from datetime import timedelta

from django.test import TestCase
from django.utils import timezone

from django.core import mail

from accounts.models import Role, User
from masters.models import Client, Inspector, JobType, Office, ReportFormat, SBU
from operations.models import CallStatus, ColourStatus, InspectionCall


class CallLogicTests(TestCase):
    @classmethod
    def setUpTestData(cls):
        cls.ahd = Office.objects.create(code="AHMEDABAD")
        cls.mum = Office.objects.create(code="MUMBAI")
        cls.sbu = SBU.objects.create(code="I03", name="Mining Energy & Power")
        cls.jt = JobType.objects.create(name="Inspection")
        cls.client_obj = Client.objects.create(name="Acme Ltd")
        cls.today = timezone.localdate()

    def _make(self, offset, status=CallStatus.PENDING_SCHEDULE, exe=None):
        return InspectionCall.objects.create(
            client=self.client_obj,
            job_type=self.jt,
            sbu=self.sbu,
            contracting_office=self.ahd,
            executing_office=exe or self.ahd,
            date_call_received=self.today - timedelta(days=2),
            date_inspection_required=self.today + timedelta(days=offset),
            status=status,
        )

    def test_ref_autogenerated_and_sequential(self):
        c1 = self._make(3)
        c2 = self._make(3)
        self.assertTrue(c1.call_ref.startswith("CALL-"))
        self.assertNotEqual(c1.call_ref, c2.call_ref)

    def test_colour_status(self):
        self.assertEqual(self._make(-1).colour_status, ColourStatus.RED)
        self.assertEqual(self._make(1).colour_status, ColourStatus.AMBER)
        self.assertEqual(self._make(10).colour_status, ColourStatus.GREEN)
        self.assertEqual(
            self._make(-5, status=CallStatus.SCHEDULED).colour_status,
            ColourStatus.GREEN,
        )

    def test_lead_time(self):
        self.assertEqual(self._make(5).lead_time_days, 7)

    def test_escalation_levels(self):
        self.assertIsNone(self._make(-1).escalation_level)
        self.assertEqual(self._make(-3).escalation_level, "BRANCH_MANAGER")
        self.assertEqual(self._make(-5).escalation_level, "SBU_HEAD")

    def test_is_network_call(self):
        self.assertTrue(self._make(3, exe=self.mum).is_network_call)
        self.assertFalse(self._make(3).is_network_call)


class WorkflowViewTests(TestCase):
    @classmethod
    def setUpTestData(cls):
        cls.ahd = Office.objects.create(code="AHMEDABAD")
        cls.sbu = SBU.objects.create(code="I03", name="Power")
        cls.jt = JobType.objects.create(name="Inspection")
        cls.client_obj = Client.objects.create(name="Acme Ltd")
        cls.inspector = Inspector.objects.create(name="Ravi Kumar")
        cls.user = User.objects.create_user(
            username="coord", password="pw", role=Role.INSPECTION_COORDINATOR,
            home_office=cls.ahd,
        )

    def setUp(self):
        self.client.login(username="coord", password="pw")

    def _call(self):
        return InspectionCall.objects.create(
            client=self.client_obj, job_type=self.jt, sbu=self.sbu,
            contracting_office=self.ahd, executing_office=self.ahd,
            date_inspection_required=timezone.localdate(),
            status=CallStatus.PENDING_SCHEDULE,
        )

    def test_board_renders(self):
        self._call()
        self.assertEqual(self.client.get("/ops/board/").status_code, 200)

    def test_allocate_flow(self):
        call = self._call()
        resp = self.client.post(
            f"/ops/calls/{call.pk}/allocate/",
            {
                "inspector": self.inspector.pk,
                "inspector_kind": "SGS_ASSET",
                "scheduled_date": str(timezone.localdate()),
            },
        )
        self.assertEqual(resp.status_code, 302)
        call.refresh_from_db()
        self.assertEqual(call.status, CallStatus.SCHEDULED)
        self.assertEqual(call.assignments.filter(is_active=True).count(), 1)

    def test_reject_records_reason(self):
        call = self._call()
        self.client.post(
            f"/ops/calls/{call.pk}/reject/", {"reason": "No inspector available"}
        )
        call.refresh_from_db()
        self.assertEqual(call.status, CallStatus.REJECTED)
        self.assertIn("No inspector", call.rejection_reason)

    def test_allocation_creates_deliverables_and_emails_inspector(self):
        call = self._call()
        call.reporting_required = True
        call.save()
        fmt = ReportFormat.objects.create(name="Inspection Report")
        call.report_formats.add(fmt)
        self.inspector.email = "insp@example.com"
        self.inspector.save()

        self.client.post(
            f"/ops/calls/{call.pk}/allocate/",
            {
                "inspector": self.inspector.pk,
                "inspector_kind": "SGS_ASSET",
                "scheduled_date": str(timezone.localdate()),
            },
        )
        # One deliverable (TAT) created, and the inspector was emailed.
        self.assertEqual(call.deliverables.count(), 1)
        self.assertTrue(call.deliverables.first().due_date)
        self.assertEqual(len(mail.outbox), 1)
        self.assertIn(call.call_ref, mail.outbox[0].subject)

    def test_deliverable_submit_marks_submitted(self):
        call = self._call()
        fmt = ReportFormat.objects.create(name="Release Note")
        d = call.deliverables.create(report_format=fmt)
        self.assertIsNone(d.submitted_at)
        self.client.post(f"/ops/deliverables/{d.pk}/submit/", {})
        d.refresh_from_db()
        self.assertIsNotNone(d.submitted_at)

    def test_my_work_requires_inspector_profile(self):
        resp = self.client.get("/ops/my-work/")
        self.assertContains(resp, "isn't linked to an inspector")
        self.user.inspector_profile = self.inspector
        self.user.save()
        resp = self.client.get("/ops/my-work/")
        self.assertContains(resp, "My Assignments")
